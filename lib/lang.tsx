const dict = { en, ur };

type DictKey = keyof typeof en;

export type { DictKey };

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: DictKey) => string }>({
  lang: 'en',
  setLang: () => {},
  t: (k) => en[k],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  useEffect(() => {
    try {
      const saved = localStorage.getItem('hamsafar-lang');
      if (saved === 'ur' || saved === 'en') setLangState(saved);
    } catch { /* ignore */ }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
    try { localStorage.setItem('hamsafar-lang', lang); } catch { /* ignore */ }
  }, [lang]);
  const t = (k: DictKey) => (dict[lang] as Record<DictKey, string>)[k] ?? en[k] ?? k;
  return <LangCtx.Provider value={{ lang, setLang: setLangState, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}
